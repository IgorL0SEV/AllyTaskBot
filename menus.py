# ------------------------------------------------------------------
# Ключи — универсальные слоты project1, project2, … (латиницей, не видны
# пользователю). Подписи справа — названия ваших проектов/категорий:
# меняйте их под свою команду. В БД сохраняется подпись справа, поэтому
# переименование подписи не ломает старые задачи (у них останется прежняя).
